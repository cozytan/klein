    member_id INT AUTO_INCREMENT PRIMARY KEY,
    full_name VARCHAR(100),
    phone VARCHAR(20),
    membership_id INT,
    join_date DATE,
    expiry_date DATE,
    FOREIGN KEY (membership_id) REFERENCES membership_types(membership_id)
);

